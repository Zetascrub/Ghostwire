// Public half of the release-signing keypair (ECDSA P-256/prime256v1),
// embedded so the device can verify a firmware release was signed by the
// maintainer before committing it to the OTA partition. See
// docs/roadmap.md item 11 and docs/ota-updates.md.
//
// This is the SubjectPublicKeyInfo DER encoding -- feed it straight to
// mbedtls_pk_parse_public_key(), no PEM/base64 handling needed on-device.
//
// The matching private key is held by the maintainer (GitHub Actions
// secret, used only by .github/workflows/release.yml to sign release
// assets) and is never present in this repository. Rotating this key
// requires shipping a new firmware build over USB with the new public key
// embedded -- there is deliberately no OTA-based way to change it, since
// that would let a compromised key rotate itself.
